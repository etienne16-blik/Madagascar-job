create table if not exists profiles(id uuid primary key references auth.users on delete cascade,email text,full_name text,balance bigint not null default 0,created_at timestamptz default now());
alter table profiles add column if not exists phone text;
alter table profiles add column if not exists status text not null default 'active' check (status in ('active','suspended'));
alter table profiles add column if not exists account_type text not null default 'user' check (account_type in ('user','business'));
alter table profiles alter column balance set default 0;
update profiles set balance=0 where balance is null;
do $$ begin alter table profiles add constraint balance_nonneg check (balance>=0); exception when others then null; end $$;

create table if not exists admin_roles(user_id uuid primary key references auth.users on delete cascade,created_at timestamptz default now());
create table if not exists businesses(id bigint generated by default as identity primary key,owner_id uuid unique not null references profiles(id) on delete cascade,name text not null,created_at timestamptz default now());
create table if not exists campaigns(id bigint generated by default as identity primary key,owner_id uuid not null references profiles(id),title text not null,description text,type text not null check(type in('social','video','screenshot','ad')),url text,media_url text,duration_seconds int not null default 15,budget bigint not null check(budget>=1000),budget_paid bigint not null default 0,spent bigint not null default 0,status text not null default 'draft' check(status in('draft','active','paused','ended')),created_at timestamptz default now(),check(spent<=budget_paid));
create table if not exists advertisements(id bigint generated by default as identity primary key,owner_id uuid references profiles(id),campaign_id bigint references campaigns(id) on delete cascade,title text,media_url text,status text not null default 'active' check(status in('active','hidden')),created_at timestamptz default now());

create table if not exists tasks(id bigint generated by default as identity primary key,title text,description text,reward bigint default 50,active boolean default true);
alter table tasks add column if not exists type text not null default 'social' check(type in('social','video','screenshot','ad'));
alter table tasks add column if not exists url text;
alter table tasks add column if not exists media_url text;
alter table tasks add column if not exists duration_seconds int not null default 15;
alter table tasks add column if not exists campaign_id bigint references campaigns(id);
alter table tasks add column if not exists ad_id bigint references advertisements(id);

create table if not exists task_completions(id bigint generated by default as identity primary key,user_id uuid references profiles(id),task_id bigint references tasks(id),completed_on date,created_at timestamptz default now());
alter table task_completions add column if not exists status text default 'approved';
alter table task_completions alter column status set default 'pending';
alter table task_completions add column if not exists reviewed_by uuid;
alter table task_completions add column if not exists reviewed_at timestamptz;
create unique index if not exists uq_completion on task_completions(user_id,task_id,completed_on);

create table if not exists task_proofs(id bigint generated by default as identity primary key,completion_id bigint unique not null references task_completions(id) on delete cascade,user_id uuid not null,content text,file_path text,created_at timestamptz default now());
create table if not exists ad_views(id bigint generated by default as identity primary key,user_id uuid not null,task_id bigint not null,started_at timestamptz not null default now(),used boolean not null default false);

create table if not exists wallet_transactions(id bigint generated by default as identity primary key,user_id uuid references profiles(id),description text,amount bigint,created_at timestamptz default now());
alter table wallet_transactions add column if not exists kind text;
create table if not exists withdrawals(id bigint generated by default as identity primary key,user_id uuid references profiles(id),amount bigint,method text,phone text,status text default 'pending',created_at timestamptz default now());
alter table withdrawals add column if not exists note text;
alter table withdrawals add column if not exists reviewed_at timestamptz;
create table if not exists deposits(id bigint generated by default as identity primary key,user_id uuid not null references profiles(id),campaign_id bigint references campaigns(id),amount bigint not null check(amount>=1000),method text default 'mvola',reference text,file_path text,status text not null default 'pending' check(status in('pending','approved','rejected')),created_at timestamptz default now(),reviewed_at timestamptz);
create unique index if not exists uq_dep_ref on deposits(lower(reference)) where reference is not null;

-- ===== Fonctions utilitaires =====
create or replace function is_admin() returns boolean language sql security definer stable set search_path=public as $$ select exists(select 1 from admin_roles where user_id=auth.uid()) $$;
create or replace function _need_admin() returns void language plpgsql security definer set search_path=public as $$ begin if not is_admin() then raise exception 'Accès refusé'; end if; end $$;
create or replace function _active_user() returns uuid language plpgsql security definer set search_path=public as $$
declare u uuid:=auth.uid(); begin
 if u is null then raise exception 'Non connecté'; end if;
 if not exists(select 1 from profiles where id=u and status='active') then raise exception 'Compte suspendu ou introuvable'; end if; return u; end $$;

-- Création automatique du profil (le type admin n'est jamais accepté depuis le client)
create or replace function handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
declare t text:=case when new.raw_user_meta_data->>'account_type'='business' then 'business' else 'user' end; n text:=left(coalesce(new.raw_user_meta_data->>'full_name',''),80);
begin
 insert into profiles(id,email,full_name,account_type) values(new.id,new.email,n,t) on conflict(id) do nothing;
 if t='business' then insert into businesses(owner_id,name) values(new.id,n) on conflict do nothing; end if;
 return new; end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function handle_new_user();
insert into profiles(id,email) select id,email from auth.users on conflict do nothing;

-- Filet de sécurité : crée le profil s'il manque (ex. trigger absent)
create or replace function ensure_profile() returns void language plpgsql security definer set search_path=public as $$
declare u auth.users; begin
 select * into u from auth.users where id=auth.uid(); if not found then raise exception 'Non connecté'; end if;
 insert into profiles(id,email,full_name,account_type) values(u.id,u.email,left(coalesce(u.raw_user_meta_data->>'full_name',''),80),case when u.raw_user_meta_data->>'account_type'='business' then 'business' else 'user' end) on conflict(id) do nothing;
 if exists(select 1 from profiles where id=u.id and account_type='business') then insert into businesses(owner_id,name) values(u.id,coalesce(u.raw_user_meta_data->>'full_name','')) on conflict do nothing; end if; end $$;

-- ===== Missions =====
create or replace function start_video(p_task bigint) returns void language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); begin
 if not exists(select 1 from tasks where id=p_task and active and type='video') then raise exception 'Vidéo indisponible'; end if;
 delete from ad_views where user_id=u and task_id=p_task and not used;
 insert into ad_views(user_id,task_id) values(u,p_task); end $$;

create or replace function submit_task(p_task bigint,p_proof text,p_path text) returns bigint language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); t tasks; n int; cid bigint; v ad_views; begin
 select * into t from tasks where id=p_task and active; if not found then raise exception 'Mission indisponible'; end if;
 select count(*) into n from task_completions where user_id=u and completed_on=current_date and status<>'rejected';
 if n>=5 then raise exception 'Limite de 5 missions par jour atteinte'; end if;
 if t.type='video' then
  select * into v from ad_views where user_id=u and task_id=p_task and not used order by id desc limit 1 for update;
  if not found or v.started_at>now()-make_interval(secs=>t.duration_seconds) then raise exception 'Visionnage incomplet'; end if;
  update ad_views set used=true where id=v.id;
 elsif t.type='social' and coalesce(p_proof,'')='' then raise exception 'Lien de publication requis';
 elsif t.type in('screenshot','ad') and p_path is null then raise exception 'Capture d''écran requise'; end if;
 if p_path is not null and split_part(p_path,'/',1)<>u::text then raise exception 'Fichier invalide'; end if;
 begin insert into task_completions(user_id,task_id,completed_on,status) values(u,p_task,current_date,'pending') returning id into cid;
 exception when unique_violation then raise exception 'Mission déjà soumise aujourd''hui'; end;
 insert into task_proofs(completion_id,user_id,content,file_path) values(cid,u,left(p_proof,1000),p_path);
 return cid; end $$;

create or replace function admin_review_completion(p_id bigint,p_ok boolean) returns void language plpgsql security definer set search_path=public as $$
declare c task_completions; t tasks; begin perform _need_admin();
 select * into c from task_completions where id=p_id for update;
 if not found or c.status<>'pending' then raise exception 'Déjà traitée'; end if;
 if not p_ok then update task_completions set status='rejected',reviewed_by=auth.uid(),reviewed_at=now() where id=p_id; return; end if;
 select * into t from tasks where id=c.task_id;
 if t.campaign_id is not null then
  update campaigns set spent=spent+t.reward where id=t.campaign_id and spent+t.reward<=budget_paid;
  if not found then raise exception 'Budget de la campagne épuisé'; end if; end if;
 update task_completions set status='approved',reviewed_by=auth.uid(),reviewed_at=now() where id=p_id;
 update profiles set balance=balance+t.reward where id=c.user_id;
 insert into wallet_transactions(user_id,description,amount,kind) values(c.user_id,'Mission : '||coalesce(t.title,'#'||t.id)||' (virtuel)',t.reward,'earning'); end $$;

-- ===== Retraits (simulés) =====
create or replace function request_withdrawal(p_amount bigint,p_method text,p_phone text) returns bigint language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); b bigint; wid bigint; begin
 if p_amount<10000 then raise exception 'Retrait minimum : 10 000 Ar'; end if;
 if p_method not in('mvola','orange','airtel') then raise exception 'Méthode invalide'; end if;
 if p_phone !~ '^0(32|33|34|37|38)[0-9]{7}$' then raise exception 'Numéro invalide'; end if;
 select balance into b from profiles where id=u for update;
 if exists(select 1 from withdrawals where user_id=u and status='pending') then raise exception 'Une demande est déjà en attente'; end if;
 if b<p_amount then raise exception 'Solde insuffisant'; end if;
 update profiles set balance=balance-p_amount where id=u;
 insert into withdrawals(user_id,amount,method,phone,status) values(u,p_amount,p_method,p_phone,'pending') returning id into wid;
 insert into wallet_transactions(user_id,description,amount,kind) values(u,'Demande de retrait #'||wid||' (simulation)',-p_amount,'withdrawal');
 return wid; end $$;

create or replace function admin_review_withdrawal(p_id bigint,p_ok boolean) returns void language plpgsql security definer set search_path=public as $$
declare w withdrawals; begin perform _need_admin();
 select * into w from withdrawals where id=p_id for update;
 if not found or w.status<>'pending' then raise exception 'Déjà traité'; end if;
 update withdrawals set status=case when p_ok then 'approved' else 'rejected' end,reviewed_at=now() where id=p_id;
 if not p_ok then update profiles set balance=balance+w.amount where id=w.user_id;
  insert into wallet_transactions(user_id,description,amount,kind) values(w.user_id,'Retrait #'||p_id||' refusé : remboursement',w.amount,'refund'); end if; end $$;

-- ===== Dépôts / paiements entreprises =====
create or replace function submit_deposit(p_amount bigint,p_method text,p_ref text,p_path text,p_campaign bigint) returns bigint language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); did bigint; begin
 if p_amount<1000 then raise exception 'Montant minimum : 1 000 Ar'; end if;
 if coalesce(p_ref,'')='' and p_path is null then raise exception 'Référence ou capture requise'; end if;
 if p_path is not null and split_part(p_path,'/',1)<>u::text then raise exception 'Fichier invalide'; end if;
 if p_campaign is not null and not exists(select 1 from campaigns where id=p_campaign and owner_id=u) then raise exception 'Campagne introuvable'; end if;
 begin insert into deposits(user_id,campaign_id,amount,method,reference,file_path) values(u,p_campaign,p_amount,'mvola',nullif(trim(p_ref),''),p_path) returning deposits.id into did;
 exception when unique_violation then raise exception 'Cette référence a déjà été utilisée'; end;
 return did; end $$;

create or replace function admin_review_deposit(p_id bigint,p_ok boolean) returns void language plpgsql security definer set search_path=public as $$
declare d deposits; begin perform _need_admin();
 select * into d from deposits where id=p_id for update;
 if not found or d.status<>'pending' then raise exception 'Déjà traité'; end if;
 update deposits set status=case when p_ok then 'approved' else 'rejected' end,reviewed_at=now() where id=p_id;
 if not p_ok then return; end if;
 if d.campaign_id is not null then update campaigns set budget_paid=budget_paid+d.amount where id=d.campaign_id; perform admin_set_campaign(d.campaign_id,'active');
 else update profiles set balance=balance+d.amount where id=d.user_id;
  insert into wallet_transactions(user_id,description,amount,kind) values(d.user_id,'Dépôt #'||p_id||' (virtuel)',d.amount,'deposit'); end if; end $$;

-- ===== Campagnes =====
create or replace function create_campaign(p_title text,p_desc text,p_type text,p_url text,p_media text,p_budget bigint,p_duration int) returns bigint language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); cid bigint; begin
 if not exists(select 1 from profiles where id=u and account_type='business') then raise exception 'Réservé aux entreprises'; end if;
 if p_type not in('social','video','screenshot','ad') then raise exception 'Type invalide'; end if;
 if p_budget<1000 then raise exception 'Budget minimum : 1 000 Ar'; end if;
 insert into campaigns(owner_id,title,description,type,url,media_url,budget,duration_seconds) values(u,left(p_title,120),left(p_desc,1000),p_type,p_url,p_media,p_budget,greatest(5,least(coalesce(p_duration,15),120))) returning id into cid;
 if p_media is not null then insert into advertisements(owner_id,campaign_id,title,media_url) values(u,cid,left(p_title,120),p_media); end if;
 return cid; end $$;

create or replace function campaign_stats(p_id bigint) returns json language plpgsql security definer set search_path=public as $$
begin if not (is_admin() or exists(select 1 from campaigns where id=p_id and owner_id=auth.uid())) then raise exception 'Accès refusé'; end if;
 return json_build_object(
  'approved',(select count(*) from task_completions c join tasks t on t.id=c.task_id where t.campaign_id=p_id and c.status='approved'),
  'pending',(select count(*) from task_completions c join tasks t on t.id=c.task_id where t.campaign_id=p_id and c.status='pending'),
  'views',(select count(*) from ad_views v join tasks t on t.id=v.task_id where t.campaign_id=p_id and v.used)); end $$;

create or replace function admin_set_campaign(p_id bigint,p_status text) returns void language plpgsql security definer set search_path=public as $$
declare c campaigns; begin perform _need_admin();
 if p_status not in('active','paused','ended') then raise exception 'Statut invalide'; end if;
 select * into c from campaigns where id=p_id for update; if not found then raise exception 'Introuvable'; end if;
 if p_status='active' and c.budget_paid<=c.spent then raise exception 'Paiement non validé ou budget épuisé'; end if;
 update campaigns set status=p_status where id=p_id;
 if p_status='active' and not exists(select 1 from tasks where campaign_id=p_id) then
  insert into tasks(title,description,type,url,media_url,duration_seconds,reward,active,campaign_id,ad_id)
  values(c.title,c.description,c.type,c.url,c.media_url,c.duration_seconds,50,true,p_id,(select id from advertisements where campaign_id=p_id limit 1));
 else update tasks set active=(p_status='active') where campaign_id=p_id; end if; end $$;

