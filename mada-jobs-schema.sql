-- L'entreprise peut mettre en pause / reprendre SA campagne (pas si l'admin l'a stoppée)
create or replace function owner_set_campaign(p_id bigint,p_status text) returns void language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); c campaigns; begin
 if p_status not in('active','paused') then raise exception 'Statut invalide'; end if;
 select * into c from campaigns where id=p_id and owner_id=u for update;
 if not found then raise exception 'Campagne introuvable'; end if;
 if p_status='paused' and c.status<>'active' then raise exception 'Action impossible'; end if;
 if p_status='active' and not (c.status='paused' and c.owner_paused) then raise exception 'Reprise impossible : contactez l''administration'; end if;
 if p_status='active' and c.budget_paid<=c.spent then raise exception 'Budget épuisé'; end if;
 update campaigns set status=p_status,owner_paused=(p_status='paused') where id=p_id;
 update tasks set active=(p_status='active' and not exists(select 1 from advertisements a where a.id=tasks.ad_id and a.status='hidden')) where campaign_id=p_id; end $$;

-- L'action admin réinitialise la pause "entreprise"
