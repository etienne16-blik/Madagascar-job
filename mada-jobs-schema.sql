create or replace function apply_referral_code(p_code text) returns void
language plpgsql security definer set search_path=public as $$
declare u uuid:=_active_user(); r profiles;
begin
 if exists(select 1 from profiles where id=u and referred_by is not null) then
  raise exception 'Code de parrainage déjà utilisé';
 end if;
 select * into r from profiles where referral_code=upper(trim(p_code)) and id<>u and status='active';
